import type { LlmClient, LlmRequest, LlmResponse } from "./types";

/**
 * A stand-in model for local development and tests (MOCK_LLM=1). It returns
 * deterministic replies built from the request, and it deliberately writes a
 * flawed first test suite so both feedback loops run.
 *
 * It is never a substitute for a live run: the UI labels mock runs clearly.
 */
export class MockLlmClient implements LlmClient {
  readonly mode = "mock" as const;
  private readonly callsByAgent = new Map<string, number>();

  constructor(private readonly delayMs: number = 600) {}

  async complete(request: LlmRequest): Promise<LlmResponse> {
    const count = (this.callsByAgent.get(request.agent) ?? 0) + 1;
    this.callsByAgent.set(request.agent, count);

    if (this.delayMs > 0) await sleep(this.delayMs, request.signal);

    const prompt = request.messages.map((message) => message.content).join("\n");
    const text = reply(request.agent, prompt, count);
    return {
      text,
      tokensIn: Math.ceil((request.system.length + prompt.length) / 4),
      tokensOut: Math.ceil(text.length / 4),
      model: `mock-${request.model}`,
      truncated: false,
    };
  }
}

function sleep(ms: number, signal?: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(resolve, ms);
    signal?.addEventListener(
      "abort",
      () => {
        clearTimeout(timer);
        reject(new Error("aborted"));
      },
      { once: true },
    );
  });
}

function between(prompt: string, tag: string): string {
  const match = new RegExp(`<${tag}>([\\s\\S]*?)</${tag}>`).exec(prompt);
  return match ? match[1].trim() : "";
}

function ids(prompt: string, prefix: string): string[] {
  const found = prompt.match(new RegExp(`\\b${prefix}-\\d+\\b`, "g")) ?? [];
  return [...new Set(found)];
}

function sentences(story: string): string[] {
  return story
    .replace(/^#.*$/gm, "")
    .split(/(?<=[.!?])\s+/)
    .map((sentence) => sentence.trim())
    .filter((sentence) => sentence.length > 20 && sentence.length < 280);
}

const VAGUE_TERMS = [
  "fast",
  "quickly",
  "secure",
  "reasonable",
  "some time",
  "strong",
  "large",
  "user-friendly",
  "an error",
  "notified",
  "easy",
  "soon",
];

function reply(agent: string, prompt: string, count: number): string {
  const story = between(prompt, "requirement");

  switch (agent) {
    case "planner":
      return JSON.stringify({
        domain: "Web application",
        summary: "Mock plan: a user-facing feature described in a short story.",
        focusAreas: ["Input validation", "Error handling", "Permissions", "State after failure"],
        riskLevel: "medium",
        notes: "Generated by the mock model.",
      });

    case "analyst": {
      const picked = sentences(story).slice(0, 4);
      const criteria = (picked.length ? picked : ["The feature works as described."]).map((sentence) => ({
        text: `The system satisfies: ${sentence}`,
        sourceQuote: sentence,
      }));
      return JSON.stringify({ criteria });
    }

    case "ambiguity": {
      const lower = story.toLowerCase();
      const hits = VAGUE_TERMS.filter((term) => lower.includes(term)).slice(0, 5);
      const ambiguities = hits.map((term, index) => {
        const sentence = sentences(story).find((candidate) => candidate.toLowerCase().includes(term)) ?? term;
        return {
          term,
          quote: sentence,
          whyItMatters: `"${term}" cannot be tested until it has a measurable definition.`,
          question: `What exactly does "${term}" mean here? Please give a number, rule or example.`,
          severity: index === 0 ? "high" : "medium",
        };
      });
      ambiguities.push({
        term: "Missing: failure behaviour",
        quote: "",
        whyItMatters: "The story does not say what state the system is left in after a failure.",
        question: "After a failed attempt, what should the user see and what should be saved?",
        severity: "medium",
      });
      return JSON.stringify({ ambiguities });
    }

    case "edgecases": {
      const acs = ids(prompt, "AC");
      const pick = (index: number) => acs[index % Math.max(acs.length, 1)] ?? "";
      return JSON.stringify({
        edgeCases: [
          { title: "Empty required field", category: "validation", relatedAC: pick(0), severity: "high", expected: "The request is rejected with a clear message." },
          { title: "Value at the upper boundary", category: "boundary", relatedAC: pick(1), severity: "medium", expected: "The boundary value is accepted; one above is rejected." },
          { title: "Same request submitted twice", category: "concurrency", relatedAC: pick(0), severity: "high", expected: "Only one result is recorded." },
          { title: "User without permission", category: "permissions", relatedAC: pick(2), severity: "medium", expected: "Access is denied and nothing changes." },
        ],
      });
    }

    case "history": {
      if (count === 1) {
        const words = (story.match(/[A-Za-z]{5,}/g) ?? ["bug"]).slice(0, 3).join(" ");
        return JSON.stringify({ queries: [words] });
      }
      const numbers = [...new Set((prompt.match(/#(\d+)/g) ?? []).map((ref) => Number(ref.slice(1))))].slice(0, 2);
      return JSON.stringify({
        summary: "Mock summary: earlier bugs in this area were mostly about edge inputs.",
        lessons: numbers.length
          ? [{ lesson: "Past bugs came from unusual inputs, so test them first.", issues: numbers }]
          : [],
      });
    }

    case "designer": {
      if (prompt.includes("Write ONLY the new scenarios")) {
        const missing = [...prompt.matchAll(/- (?:High-severity edge case )?((?:AC|EC)-\d+) has no scenario/g)].map((match) => match[1]);
        const scenarios = missing.map((id) =>
          [`  @${id.startsWith("EC") ? `AC-1 @${id}` : id}`, `  Scenario: Added coverage for ${id}`, "    Given a signed-in user on the feature page", `    When the user does what ${id} describes`, "    Then the expected result is shown"].join("\n"),
        );
        return "```gherkin\n" + scenarios.join("\n\n") + "\n```";
      }
      return "```gherkin\n" + mockFeature(ids(prompt, "AC"), ids(prompt, "EC"), count) + "\n```";
    }

    case "skeptic":
      return JSON.stringify({
        verdict: "revise",
        issues: [
          {
            scenario: "Happy path",
            problem: "There is no negative scenario showing the system state after a failure.",
            fix: "Add a scenario where the action fails and assert that nothing was saved.",
            severity: "major",
          },
        ],
        strengths: ["Every acceptance criterion has a tagged scenario."],
      });

    case "ranker": {
      const scenarioIds = [...new Set(prompt.match(/\bS\d+\b/g) ?? [])];
      return JSON.stringify({
        ranking: scenarioIds.map((id, index) => ({
          id,
          priority: index < 2 ? "P1" : index < 5 ? "P2" : "P3",
          reason: index < 2 ? "Core flow: a failure here blocks the feature." : "Supporting behaviour.",
        })),
      });
    }

    default:
      return "{}";
  }
}

/**
 * Round 1 leaves the last criterion uncovered and one scenario without a Then
 * step, so the Validator has something to send back. Round 2 fixes both.
 * Round 3 (after the Skeptic) adds the negative scenario it asked for.
 */
function mockFeature(acs: string[], ecs: string[], round: number): string {
  const criteria = acs.length ? acs : ["AC-1"];
  const covered = round === 1 && criteria.length > 1 ? criteria.slice(0, -1) : criteria;
  const lines: string[] = ["Feature: Mock feature under test", "  Generated by the mock model for local development.", ""];

  covered.forEach((ac, index) => {
    lines.push(`  @${ac}`);
    lines.push(`  Scenario: Happy path for ${ac}`);
    lines.push("    Given a signed-in user on the feature page");
    lines.push(`    When the user completes the action described by ${ac}`);
    if (!(round === 1 && index === 0)) {
      lines.push("    Then the result is shown on screen");
      lines.push("    And the change is saved");
    }
    lines.push("");
  });

  ecs.forEach((ec, index) => {
    lines.push(`  @${covered[index % covered.length]} @${ec}`);
    lines.push(`  Scenario: Edge case ${ec} is handled`);
    lines.push(`    Given the conditions for ${ec}`);
    lines.push("    When the user submits the form");
    lines.push("    Then a clear error message is shown");
    lines.push("");
  });

  if (round >= 3) {
    lines.push(`  @${criteria[0]}`);
    lines.push("  Scenario: Failed action leaves no partial data");
    lines.push("    Given a signed-in user on the feature page");
    lines.push("    When the action fails on the server");
    lines.push("    Then an error message is shown");
    lines.push("    And nothing is saved");
    lines.push("");
  }

  return lines.join("\n").trimEnd();
}
